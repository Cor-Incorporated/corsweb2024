#!/usr/bin/env node
import { readdir, readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { findServerOutputRemnants, findUnreachableBundles } from './dist-bundle-reachability.mjs';

// 監査する出力先（既定は ./dist）。CI はカレンダーありの 2 回目のビルド（$RUNNER_TEMP/dist-calendar）も
// AUDIT_DIST_DIR で渡して監査する（.github/workflows/ci.yml）。
const DIST_DIR = path.resolve(process.env.AUDIT_DIST_DIR || 'dist');
const TEXT_EXTENSIONS = new Set([
  '.css',
  '.html',
  '.js',
  '.json',
  '.mjs',
  '.svg',
  '.txt',
  '.webmanifest',
  '.xml',
]);
const REQUIRED_SEO_PAGES = ['index.html', 'blog/index.html', 'news/index.html', 'works/index.html', 'security/index.html'];
const ALLOWED_LOCAL_STORAGE_KEYS = new Set(['theme']);
const ALLOWED_HTTP_HOSTS = new Set(['www.w3.org']);
const ALLOWED_ORIGINS = new Set([
  // XML namespace URLs generated by sitemap tooling.
  'http://www.google.com',
  'http://www.sitemaps.org',
  'http://www.w3.org',
  // Editorial code sample in the VOICEVOX/zundamon article, not a live endpoint.
  'http://localhost:50021',
  // Public case-study link kept in i18n content.
  'https://digital-studio-c5abe.web.app',
]);
const BLOCKED_HOST_PATTERNS = [
  /^localhost$/i,
  /^127\./,
  /^0\.0\.0\.0$/,
  /^\[::1\]$/i,
  /^cor-jp-main(?:--[a-z0-9-]+)?\.web\.app$/i,
  /^cor-jp-main(?:--[a-z0-9-]+)?\.firebaseapp\.com$/i,
];

const SECRET_PATTERNS = [
  { name: 'private key', pattern: /-----BEGIN [A-Z ]*PRIVATE KEY-----/ },
  { name: 'github token', pattern: /\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9_]{20,}\b/ },
  { name: 'github fine-grained token', pattern: /\bgithub_pat_[A-Za-z0-9_]{40,}\b/ },
  { name: 'openai-style secret', pattern: /\bsk-[A-Za-z0-9_-]{20,}\b/ },
  { name: 'anthropic secret', pattern: /\bsk-ant-[A-Za-z0-9_-]{20,}\b/ },
  { name: 'slack token', pattern: /\bxox[baprs]-[A-Za-z0-9-]{20,}\b/ },
  { name: 'resend token', pattern: /\bre_[A-Za-z0-9]{20,}\b/ },
];

const walk = async dir => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(fullPath)));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
};

const readTextFiles = async files => {
  const result = [];
  for (const file of files) {
    if (!TEXT_EXTENSIONS.has(path.extname(file))) continue;
    const text = await readFile(file, 'utf8');
    result.push({ file, relative: path.relative(DIST_DIR, file), text });
  }
  return result;
};

const hasTag = (html, tag, attr, value) => {
  const pattern = new RegExp(`<${tag}\\b(?=[^>]*\\b${attr}=["']?${value}["']?)[^>]*>`, 'i');
  return pattern.test(html);
};

const hasMeta = (html, attr, value) => hasTag(html, 'meta', attr, value);
const hasLink = (html, attr, value) => hasTag(html, 'link', attr, value);

const auditSeoPage = async (violations, relativePath) => {
  const filePath = path.join(DIST_DIR, relativePath);
  const html = await readFile(filePath, 'utf8');
  const required = [
    ['meta name=description', () => hasMeta(html, 'name', 'description')],
    ['canonical link', () => hasLink(html, 'rel', 'canonical')],
    ['og:title', () => hasMeta(html, 'property', 'og:title')],
    ['og:description', () => hasMeta(html, 'property', 'og:description')],
    ['og:image', () => hasMeta(html, 'property', 'og:image')],
    ['twitter:card', () => hasMeta(html, 'name', 'twitter:card')],
    ['twitter:image', () => hasMeta(html, 'name', 'twitter:image')],
  ];

  for (const [label, check] of required) {
    if (!check()) {
      violations.push(`[dist-security] ${relativePath} is missing ${label}.`);
    }
  }
};

const auditJsonLd = (violations, file) => {
  const scriptPattern =
    /<script\b(?=[^>]*type=["']?application\/ld\+json["']?)[^>]*>([\s\S]*?)<\/script>/gi;
  let match;
  while ((match = scriptPattern.exec(file.text)) !== null) {
    const payload = match[1].trim();
    if (!payload) {
      violations.push(`[dist-security] ${file.relative} has an empty JSON-LD script.`);
      continue;
    }
    if (/<\/script/i.test(payload)) {
      violations.push(`[dist-security] ${file.relative} JSON-LD contains a raw </script> sequence.`);
      continue;
    }
    try {
      JSON.parse(payload);
    } catch (error) {
      violations.push(`[dist-security] ${file.relative} has invalid JSON-LD: ${error.message}`);
    }
  }
};

const auditSecrets = (violations, file) => {
  for (const secret of SECRET_PATTERNS) {
    if (secret.pattern.test(file.text)) {
      violations.push(`[dist-security] ${file.relative} contains possible ${secret.name}.`);
    }
  }
};

const auditOrigins = (violations, file) => {
  const urlPattern = /https?:\/\/[^\s"'<>\\)]+/g;
  for (const rawUrl of file.text.match(urlPattern) ?? []) {
    const cleaned = rawUrl.replace(/[.,;:]+$/, '');
    let url;
    try {
      url = new URL(cleaned);
    } catch {
      continue;
    }
    if (ALLOWED_ORIGINS.has(url.origin)) {
      continue;
    }
    if (url.protocol === 'http:' && !ALLOWED_HTTP_HOSTS.has(url.hostname)) {
      violations.push(`[dist-security] ${file.relative} contains non-HTTPS origin: ${url.origin}`);
    }
    if (BLOCKED_HOST_PATTERNS.some(pattern => pattern.test(url.hostname))) {
      violations.push(`[dist-security] ${file.relative} contains blocked deploy/dev origin: ${url.origin}`);
    }
  }
};

const auditLocalStorage = (violations, file) => {
  const storagePattern = /localStorage\.setItem\(\s*['"]([^'"]+)['"]/g;
  let match;
  while ((match = storagePattern.exec(file.text)) !== null) {
    const key = match[1];
    if (!ALLOWED_LOCAL_STORAGE_KEYS.has(key)) {
      violations.push(`[dist-security] ${file.relative} stores unexpected localStorage key: ${key}`);
    }
  }
};

const auditHeavyRuntime = (violations, file) => {
  if (!file.relative.startsWith('_astro/') || !file.relative.endsWith('.js')) return;
  const heavyRuntimePatterns = [
    /React\.createElement/,
    /__REACT_DEVTOOLS_GLOBAL_HOOK__/,
    /react-dom/i,
    /vue\.runtime/i,
    /svelte\/internal/i,
  ];
  if (heavyRuntimePatterns.some(pattern => pattern.test(file.text))) {
    violations.push(`[dist-security] ${file.relative} appears to include a heavy UI runtime.`);
  }
};

// サーバー描画（SSR）チャンクが公開ディレクトリ _astro に残っていないこと（Epic #330 / #337）。
// vite の rollupOptions.output で出力名を上書きすると SSR ビルドにも効き、記事本文を含むチャンクが
// _astro/*.js として公開されていた。HTML から参照されないので表示は壊れず、目視では気づけない。
// 目印（createComponent 等）の無いチャンクもあるため、主判定は下の到達可能性（auditBundleReachability）で行い、
// これは補助の判定として残す。
const SERVER_RENDER_MARKERS = /\bcreateComponent\b|\brenderTemplate\b/;
const auditServerRenderChunks = (violations, file) => {
  if (!file.relative.startsWith('_astro/') || !file.relative.endsWith('.js')) return;
  if (SERVER_RENDER_MARKERS.test(file.text)) {
    violations.push(`[dist-security] ${file.relative} is a server-render chunk (createComponent/renderTemplate) published under _astro/.`);
  }
};

// 公開 _astro/*.js がどの HTML からも辿れない（取り残し）/ サーバービルドの残骸（.mjs・chunks/）が無いこと。
const auditBundleReachability = async (violations, files) => {
  for (const relative of await findUnreachableBundles(DIST_DIR, files)) {
    violations.push(`[dist-security] ${relative} is published under _astro/ but no HTML page loads it (leftover build output).`);
  }
  for (const relative of findServerOutputRemnants(DIST_DIR, files)) {
    violations.push(`[dist-security] ${relative} looks like server build output (.mjs / chunks/) left in dist.`);
  }
};

const main = async () => {
  const distStat = await stat(DIST_DIR).catch(() => null);
  if (!distStat?.isDirectory()) {
    throw new Error(`[dist-security] ${DIST_DIR} not found. Run npm run build first (or set AUDIT_DIST_DIR).`);
  }

  const files = await walk(DIST_DIR);
  const textFiles = await readTextFiles(files);
  const violations = [];

  for (const page of REQUIRED_SEO_PAGES) {
    await auditSeoPage(violations, page);
  }

  for (const file of textFiles) {
    auditJsonLd(violations, file);
    auditSecrets(violations, file);
    auditOrigins(violations, file);
    auditLocalStorage(violations, file);
    auditHeavyRuntime(violations, file);
    auditServerRenderChunks(violations, file);
  }
  await auditBundleReachability(violations, files);

  if (violations.length > 0) {
    throw new Error(violations.join('\n'));
  }

  console.log(
    `[dist-security] dist baseline passed (${files.length} files, ${textFiles.length} text assets, ${REQUIRED_SEO_PAGES.length} SEO pages).`
  );
};

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
